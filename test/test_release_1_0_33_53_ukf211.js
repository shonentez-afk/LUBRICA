const fs=require('fs'),vm=require('vm'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const window={LubricaSystem:{registerModule(){}}};window.window=window;
const ctx={window,console};vm.createContext(ctx);
for(const f of ['bearings/catalog-data.js','bearings/library.js','bearings/multi-oem-data.js'])vm.runInContext(fs.readFileSync(path.join(root,f),'utf8'),ctx,{filename:f});
const B=window.LubricaBearings, OEM=window.LubricaBearingOEM;
let r=B.lookup('Узел подшипниковый UKF 211');
assert(r.record,'UKF211 must resolve from built-in library');
assert.strictEqual(r.record.designation,'UKF211');
assert.strictEqual(r.record.bearingType,'bearing_unit');
assert.strictEqual(r.record.insertDesignation,'UK211');
assert.strictEqual(r.record.adapterSleeve,'H2311');
assert.deepStrictEqual([r.record.d,r.record.D,r.record.B],[50,100,59]);
assert.strictEqual(r.record.unitMassKg,3.6);
assert.strictEqual(r.parsed.baseDesignation,'UKF211');
assert.strictEqual(r.parsed.recognized,true);
assert.strictEqual(r.parsed.inferredType,'bearing_unit');
assert(B.search('UKF211').some(x=>x.designation==='UKF211'),'UKF211 must be visible in library search');
assert(B.search('UKF 211').some(x=>x.designation==='UKF211'),'UKF 211 spaced alias must be searchable');
const nsk=OEM.nskBearingUnitProfile('UKF211');
assert(nsk && nsk.exactInsert,'NSK UKF211 must resolve UK211 insert');
assert.strictEqual(nsk.insertDesignation,'UK211D1');
assert.strictEqual(nsk.adapterSleeve,'H2311X');
assert.strictEqual(nsk.unitMassKg,3.6);
assert.strictEqual(nsk.exactUnitMass,true);
assert.strictEqual(nsk.unitGeometry.L,162);
assert.strictEqual(nsk.unitGeometry.J,130);
const ref=OEM.housedUnitReferenceProfile('UKF211');
assert(ref && ref.code==='211','UKF211 must retain housed-unit reference code 211');
assert.strictEqual(ref.relubeG,6.0);
console.log('PASS 1.0.33.53 UKF211 housed bearing unit library');
