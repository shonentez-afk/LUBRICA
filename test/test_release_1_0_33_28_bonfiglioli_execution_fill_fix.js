const assert=require('assert');
const fs=require('fs');
const path=require('path');
const vm=require('vm');
const root=path.resolve(__dirname,'..');
const src=fs.readFileSync(path.join(root,'components/starter-data.js'),'utf8');
const ctx={window:{}}; vm.createContext(ctx); vm.runInContext(src,ctx);
const data=ctx.window.LubricaComponentStarterData||[];
const by=id=>data.find(x=>x.id===id);
const rec=by('STD-GBX-BONF-C412-U-11_2-P112-B5');
assert(rec,'C412 11.2 B5 profile missing');
assert.equal(rec.technicalData.fixedFillLiters,2.4);
assert.equal(rec.technicalData.fillVolumeKey,'BONFIGLIOLI:C412:B5');
assert.equal(rec.technicalData.executionDoesNotAffectFill,true);
assert.equal(rec.lubricationData.fillPolicy,'catalog_fixed');
assert(rec.aliases.includes('C412/UFB 1:11,2 B5 PAM 112'));
assert(rec.aliases.includes('C412/U 1:11,2 B5 PAM 112'));
assert(!('referenceFillLiters' in rec.technicalData));
assert(!('fillVerificationRequired' in rec.technicalData));
const schema=fs.readFileSync(path.join(root,'core/database-schema.js'),'utf8');
assert(schema.includes("appVersion:'1.0.33.39'"));
console.log('PASS 1.0.33.28 Bonfiglioli U/UFB fill-volume equivalence');
