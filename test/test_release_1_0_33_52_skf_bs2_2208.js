const fs=require('fs'),vm=require('vm'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const window={LubricaSystem:{registerModule(){}}};window.window=window;
const ctx={window,console};vm.createContext(ctx);
for(const f of ['bearings/catalog-data.js','bearings/library.js'])vm.runInContext(fs.readFileSync(path.join(root,f),'utf8'),ctx,{filename:f});
const B=window.LubricaBearings;
let r=B.lookup('Подшипник BS2-2208-2CS/VT143');
assert(r.record,'BS2-2208-2CS/VT143 must resolve from built-in library');
assert.strictEqual(r.record.designation,'BS2-2208-2CS/VT143');
assert.strictEqual(r.record.manufacturer,'SKF');
assert.strictEqual(r.record.bearingType,'spherical_roller');
assert.deepStrictEqual([r.record.d,r.record.D,r.record.B],[40,80,28]);
assert.strictEqual(r.record.massKg,0.57);
assert.strictEqual(r.parsed.sealing,'sealed');
assert.strictEqual(r.parsed.sealingCode,'2CS');
assert.strictEqual(r.parsed.greaseCode,'VT143');
assert.strictEqual(r.parsed.recognized,true);
assert(B.search('BS2-2208-2CS/VT143').some(x=>x.designation==='BS2-2208-2CS/VT143'),'bearing must be visible in library search');
console.log('PASS 1.0.33.52 SKF BS2-2208-2CS/VT143 library');
