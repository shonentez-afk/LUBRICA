const fs=require('fs');
const vm=require('vm');
const assert=require('assert');
const adapter=fs.readFileSync('calculations/gearbox-oil-adapter.js','utf8');
const arch=fs.readFileSync('calculations/gearbox-architecture.js','utf8');
const demo=fs.readFileSync('data/demo-data.js','utf8');
const schema=fs.readFileSync('core/database-schema.js','utf8');
const manifest=JSON.parse(fs.readFileSync('manifest.json','utf8'));
assert(adapter.includes("const explicitIntervalMode=c.intervalModeExplicit===true"),'explicit interval mode lifecycle missing');
assert(/ROSSI/.test(adapter.match(/savedLooksOem=.*?;/s)?.[0]||''),'Rossi must be recognized as OEM saved interval');
assert(adapter.includes("if(isRossi&&base!=='unknown')"),'Rossi auto interval branch missing');
assert(adapter.includes("intervalModeExplicit:intervalModeTouched||c.intervalModeExplicit===true"),'explicit user override persistence missing');
assert(arch.includes("syntheticNormalHours:18000") && arch.includes("mineralNormalHours:8000"),'Rossi interval policy missing');
assert(demo.includes('APP_VERSION="1.0.33.45"'),'runtime version mismatch');
assert(schema.includes("appVersion:'1.0.33.45'"),'database default version mismatch');
assert.equal(manifest.appVersion,'1.0.33.45');
const sandbox={window:{LubricaSystem:{registerModule(){}}}}; vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('components/starter-data.js','utf8'),sandbox);
const row=sandbox.window.LubricaComponentStarterData.find(r=>r.id==='STD-GBX-ROSSI-MRV63-16');
assert(row,'Rossi MRV63 entry missing');
assert.equal(row.lubricationData.oilBaseType,'synthetic');
assert.equal(row.lubricationData.rossiSyntheticChangeHours.normal,18000);
assert.equal(row.lubricationData.rossiSyntheticChangeHours.high,12500);
console.log('PASS gearbox OEM interval default + version sync');
