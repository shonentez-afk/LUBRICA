const fs=require('fs'),vm=require('vm'),assert=require('assert'),path=require('path');
const base=path.join(__dirname,'..');
const fanCode=fs.readFileSync(path.join(base,'fans/fan-bearing-arrangement.js'),'utf8');
let seq=0;
const sandbox={window:{LubricaCore:{IDs:{nextFrom:(arr,prefix,pad)=>`${prefix}-${String(++seq).padStart(pad,'0')}`}}},console};
sandbox.window.window=sandbox.window;vm.createContext(sandbox);vm.runInContext(fanCode,sandbox);
const F=sandbox.window.LubricaFanBearingArrangement;
const db={components:[]};const eq={id:'EQ-M1',origin:'manual',externalCode:'V-M1',name:'Вентилятор ручной'};
let assets=F.ensureManualAssets(db,eq,{fanName:'Вентилятор E TEST',motorName:'Электродвигатель M TEST'});
assert.ok(assets.fan&&assets.motor,'manual fan must create Fan Asset + Motor Asset');
assert.equal(assets.fan.candidateEquipmentType,'fan');assert.equal(assets.motor.candidateEquipmentType,'motor');
assert.equal(db.components.length,2);
assets=F.ensureManualAssets(db,eq,{fanName:'Вентилятор E TEST 2',motorName:'Электродвигатель M TEST 2'});
assert.equal(db.components.length,2,'manual asset update must not duplicate components');
assert.equal(assets.fan.name,'Вентилятор E TEST 2');assert.equal(assets.motor.name,'Электродвигатель M TEST 2');
const imported={id:'EQ-I',origin:'import'};const db2={components:[{id:'CF',equipmentId:'EQ-I',name:'Вентилятор E OEM',status:'active'},{id:'CM',equipmentId:'EQ-I',name:'Электродвигатель M OEM',status:'active'}]};
const before=JSON.stringify(db2.components);F.ensureManualAssets(db2,imported,{fanName:'X',motorName:'Y'});assert.equal(JSON.stringify(db2.components),before,'imported assets must not be rewritten by manual helper');
const entity=fs.readFileSync(path.join(base,'structure/entity-dialogs.js'),'utf8');
assert.ok(entity.includes('fanAssetName'));assert.ok(entity.includes('motorAssetName'));assert.ok(entity.includes('ensureManualAssets'));
const tree=fs.readFileSync(path.join(base,'structure/tree-ui.js'),'utf8');
assert.ok(tree.includes('generatedMotorNodes'));assert.ok(tree.includes('isMotor&&!isFan'));
assert.ok(fanCode.includes('Без Motor Asset прямой привод подтверждать нельзя'));
console.log('PASS 1.0.28.6 Manual Fan/Motor Parity');
